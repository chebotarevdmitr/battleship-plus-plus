#pragma once // гарантирует, что заголовочный файл будет включен только один раз в процессе компиляции  

#include <stdexcept> // для std::invalid_argument библиотеки исключений
#include <string> // для std::to_string библиотеки строк

namespace battleship::core {// пространство имен для организации кода и предотвращения конфликтов имен
     
constexpr int BOARD_SIZE = 10;
constexpr int MIN_COORDINATE = 0;
constexpr int MAX_COORDINATE = BOARD_SIZE - 1; 
// Класс для представления координат на игровом поле
// Класс Coordinate представляет координаты на игровом поле
//корстанты  constexpr int BOARD_SIZE = 10  Размер игрового поля,  constexpr int MIN_COORDINATE = 0 Минимальная координата,  constexpr int .
// MAX_COORDINATE = BOARD_SIZE - 1 Максимальная координата
// Константы. constexpr означает, что эти значения известны ещё до запуска программы.
// Это делает код быстрым и защищает от опечаток (никаких "магических чисел" вроде 10 или 9 в коде).

class Coordinate {
public:
    // 1. Удалённый конструктор по умолчанию
    // Мы ЗАПРЕЩАЕМ создавать координату без указания значений (например, Coordinate c;).
    // Это защищает от появления "мусорных" или неинициализированных координат в игре.
    // Игровая клетка всегда должна иметь осмысленные X и Y.
    Coordinate() = delete; 

    // 2. Основной конструктор
    // Принимает координаты X и Y. Его реализация (тело) будет в .cpp файле.
    // Именно внутри него мы вызовем validate(), чтобы убедиться, что числа от 0 до 9.
    Coordinate(int coord_x, int coord_y);

    // Современный синтаксис с trailing return type (auto ... -> type)
    // 3. Геттеры (методы получения значений) с современными спецификаторами C++
    // [[nodiscard]]: предупреждает компилятор, что результат функции нельзя игнорировать.
    //                Если ты напишешь просто coord.getX(); без присваивания, компилятор выдаст предупреждение.
    // auto ... -> int: современный синтаксис возврата типа (trailing return type). 
    //                  Читается как "функция getX, которая не изменяет объект (const), 
    //                  не выбрасывает исключений (noexcept), возвращает int".
    // const: гарантирует, что этот метод не изменит поля объекта (x_ и y_).
    // noexcept: обещает компилятору, что функция никогда не выбросит исключение. 
    //           Это позволяет компилятору оптимизировать код, делая его быстрее.
    [[nodiscard]] auto getX() const noexcept -> int { return x_; }
    [[nodiscard]] auto getY() const noexcept -> int { return y_; }

    // 4. Перегрузка оператора равенства (==)
    // Позволяет писать в коде: if (coord1 == coord2) { ... }
    // Сравниваем оба поля. Если они совпадают, координаты равны.
    [[nodiscard]] auto operator==(const Coordinate& other) const noexcept -> bool {
        return x_ == other.x_ && y_ == other.y_;
    }
   
    // 5. Перегрузка оператора неравенства (!=)
    // Мы не пишем логику сравнения заново, а просто используем уже написанный operator==.
    // Это принцип DRY (Don't Repeat Yourself) – не повторяйся
    [[nodiscard]] auto operator!=(const Coordinate& other) const noexcept -> bool {
        return !(*this == other);
    }

private:

    // 6. Закрытые поля данных (инкапсуляция)
    // Никто извне не может напрямую изменить x_ или y_ (например, coord.x_ = 100; вызовет ошибку).
    // Изменять их можно только через конструктор, что гарантирует контроль над данными.
    // {0} – это uniform initialization (унифицированная инициализация). 
    // Даже если бы конструктор по умолчанию не был удалён, поля начинали бы жизнь с безопасного значения 0.
    int x_{0};
    int y_{0};

    // 7. Статический метод валидации
    // static означает, что этот метод принадлежит самому классу, а не конкретному объекту.
    // Это идеально для проверки: нам не нужно создавать объект, чтобы проверить, 
    // являются ли переданные числа допустимыми координатами.
    // Если coord_x или coord_y выходят за пределы 0..9, этот метод выбросит std::invalid_argument.
    // Переименовали параметры для удовлетворения readability-identifier-length
    static void validate(int coord_x, int coord_y);
};
} 